  // Web Audio Synth for instant preview playback
  audioContext: null,
  activeOscillator: null,

  playPreview(songId) {
    this.stopPreview();
    try {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      if (!AudioCtx) return;
      this.audioContext = new AudioCtx();
      const osc = this.audioContext.createOscillator();
      const gain = this.audioContext.createGain();

      osc.type = "sine";
      // Pick pleasant musical notes based on songId
      const notes = [261.63, 293.66, 329.63, 392.00, 440.00, 523.25];
      const noteIdx = Math.abs(songId.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0)) % notes.length;
      osc.frequency.setValueAtTime(notes[noteIdx], this.audioContext.currentTime);

      gain.gain.setValueAtTime(0.08, this.audioContext.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, this.audioContext.currentTime + 3);

      osc.connect(gain);
      gain.connect(this.audioContext.destination);
      osc.start();
      this.activeOscillator = osc;
    } catch (e) {
      console.warn("Audio preview playback not supported", e);
    }
  },

  stopPreview() {
    if (this.activeOscillator) {
      try { this.activeOscillator.stop(); } catch(e){}
      this.activeOscillator = null;
    }
    if (this.audioContext) {
      try { this.audioContext.close(); } catch(e){}
      this.audioContext = null;
    }
  }
